//! `asaroton livekit-config`: the SFU's configuration file, derived from `[rtc.livekit]` so the
//! key, secret, webhook address, ports and TURN settings are written once and cannot drift.

use std::{fmt::Write as _, path::Path};

use crate::config::{Config, LivekitConfig};

const WEBHOOK_PATH: &str = "/_matrix/client/unstable/io.element.msc4195/rtc/livekit/sfu_webhook";

/// Writes the `livekit.yaml` for this server's SFU to standard output.
pub fn print(config: &Config, config_path: &Path) -> anyhow::Result<()> {
    let Some(lk) = &config.rtc.livekit else {
        anyhow::bail!(
            "[rtc.livekit] is not configured in {}",
            config_path.display()
        );
    };
    let client = &config.listeners.client;
    let scheme = if client.tls().is_some() {
        "https"
    } else {
        "http"
    };
    let webhook_url = format!("{scheme}://{}{WEBHOOK_PATH}", client.bind);
    let sfu = &lk.sfu;
    let public_base_url = config.public_base_url();

    let mut out = String::new();
    writeln!(
        out,
        "# LiveKit SFU configuration generated by `asaroton livekit-config` from {}.",
        config_path.display()
    )?;
    out.push_str("# Edit [rtc.livekit] there and regenerate instead of changing this file.\n");
    writeln!(out, "port: {}", sfu.port)?;
    if sfu.bind != "0.0.0.0" && sfu.bind != "::" {
        writeln!(out, "bind_addresses:\n  - {}", yaml_str(&sfu.bind))?;
    }
    writeln!(
        out,
        "rtc:\n  tcp_port: {}\n  port_range_start: {}\n  port_range_end: {}\n  use_external_ip: {}",
        sfu.tcp_port, sfu.udp_ports.0, sfu.udp_ports.1, sfu.external_ip
    )?;
    writeln!(
        out,
        "keys:\n  {}: {}",
        yaml_str(&lk.api_key),
        yaml_str(&lk.api_secret)
    )?;
    writeln!(
        out,
        "webhook:\n  api_key: {}\n  urls:\n    - {}",
        yaml_str(&lk.api_key),
        yaml_str(&webhook_url)
    )?;
    out.push_str("room:\n  auto_create: true\n");
    if let Some(turn) = lk.turn.as_ref().filter(|t| t.enabled) {
        let domain = turn.domain.as_deref().unwrap_or_else(|| {
            LivekitConfig::host_of(lk.url.as_deref().unwrap_or(&public_base_url))
        });
        writeln!(
            out,
            "turn:\n  enabled: true\n  domain: {}\n  tls_port: {}\n  cert_file: {}\n  key_file: {}",
            yaml_str(domain),
            turn.tls_port,
            yaml_str(&turn.cert_file.display().to_string()),
            yaml_str(&turn.key_file.display().to_string())
        )?;
        if !turn.allow_peer_cidrs.is_empty() {
            out.push_str("  allow_restricted_peer_cidrs:\n");
            for cidr in &turn.allow_peer_cidrs {
                writeln!(out, "    - {}", yaml_str(cidr))?;
            }
        }
        if turn.tls_port != 443 && lk.url.is_some() {
            eprintln!(
                "warning: with rtc.livekit.url set, clients bypass asaroton's signalling proxy and \
                 LiveKit will tell them to use {domain}:443 for TURN, not port {}; unset url or \
                 use tls_port = 443",
                turn.tls_port
            );
        }
        for path in [&turn.cert_file, &turn.key_file] {
            if !path.exists() {
                eprintln!(
                    "warning: {} does not exist yet; livekit-server will not start without it",
                    path.display()
                );
            }
        }
    }
    print!("{out}");
    Ok(())
}

/// A double-quoted YAML scalar.
fn yaml_str(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}
